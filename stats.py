import os

import pandas as pd

# Папка, где лежит эта программа (parser). Журнал ищем рядом с ней,
# поэтому запускать можно из любой папки
BASE = os.path.dirname(os.path.abspath(__file__))
LOG_PATH = os.path.join(BASE, "radar_log.csv")

# Если радар ещё ни разу не запускался, журнала нет — говорим об этом и выходим
if not os.path.exists(LOG_PATH):
    print("Журнала radar_log.csv нет. Сначала запусти python radar.py")
    raise SystemExit

# Читаем журнал: колонки разделены точкой с запятой, как пишет radar.py
df = pd.read_csv(LOG_PATH, sep=";")

# «Найдено» сейчас просто текст "2026-11-04 18:27" — превращаем его в дату,
# чтобы можно было сравнивать «раньше / позже»
df["Найдено"] = pd.to_datetime(df["Найдено"])

# Граница: текущий момент минус 7 дней
week_ago = pd.Timestamp.now() - pd.Timedelta(days=7)

# Оставляем только строки, найденные за последние 7 дней
df = df[df["Найдено"] >= week_ago]

if df.empty:
    print("За 7 дней предложений нет")
else:
    print(f"Предложений за 7 дней: {len(df)}\n")

    # Сколько предложений пришло из каждого чата (от большего к меньшему)
    print("По чатам:")
    print(df["Чат"].value_counts().to_string())

    # Культуры: отдельной колонки нет, ищем основу слова в тексте объявления.
    # Текст переводим в маленькие буквы, чтобы «Пшеница» и «пшеница» совпадали.
    # Знак | значит «или»: "лён|льна|лен" поймает все варианты написания
    print("\nПо культурам:")
    low = df["Текст"].str.lower()
    crops = {
        "Пшеница": "пшениц",
        "Ячмень": "ячмен",
        "Подсолнечник": "подсолн",
        "Кукуруза": "кукуруз",
        "Лён": "лён|льна|лен",
        "Рапс": "рапс",
    }
    for name, pattern in crops.items():
        # str.contains даёт True/False по каждой строке, sum() считает количество True.
        # na=False — пустой текст считаем «не содержит»
        count = low.str.contains(pattern, na=False).sum()
        print(f"{name:14} {count}")

    # Самые активные дни — видно, когда фермеры чаще выкладывают объявления
    print("\nПо дням:")
    print(df["Найдено"].dt.strftime("%Y-%m-%d").value_counts().sort_index().to_string())
